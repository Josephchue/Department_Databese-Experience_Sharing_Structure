# -*- coding: utf-8 -*-
"""规则版打标器：正文进，标签出。

整个模块**没有副作用**：不读数据库、不发 HTTP、不读文件。
所以它能被秒级测完，也是这套东西敢在服务器上批量跑的前提。

═══════════════════════════════════════════════════════════════════
  「只补空」为什么不写在文档里，而是写进结构里
═══════════════════════════════════════════════════════════════════

打标最容易出的事故是**覆盖人工标签**：有人认真写过的标签，
被一条规则脚本顺手改成了它认出来的那几个词，而且不报错。

这里用两层保底，任一层单独都够，两层是为了「改错了也不至于毁数据」：

  ① 调用方（cli/exp.py 的 run_tag）逐条判断 `if metadata["tags"]: 跳过`。
     ——这是**校验**层。
  ② 本模块的 `tag()` **只返回「要打什么」，没有任何「写入」动作**，
     返回类型是 `list[str]` 而不是「新 metadata」。
     ——这是**结构**层：想覆盖也没有可覆盖的入口。

②比①更重要。①靠人记得写，②是写不出来。

═══════════════════════════════════════════════════════════════════
  幂等（同一条经验跑两遍，第二遍不该再发一个请求）
═══════════════════════════════════════════════════════════════════

同样两层：

  ① `tag()` 是**正文的纯函数**，输出顺序固定（见 keywords.py 的 dict 保序说明）。
     同一条正文，今天和明天返回的标签列表逐项相等。
  ② 第一遍打完之后标签非空，第二遍在调用方的跳过滤那儿就拦住了
     ——第二遍发出的 PATCH 请求数是 **0**。

所以「重跑一遍」永远安全：能重跑的东西才敢在服务器上挂着。

═══════════════════════════════════════════════════════════════════
  实测：种子语料 8 条，人工标签全被覆盖，另外多打了 4 个
═══════════════════════════════════════════════════════════════════

拿 scripts/seed.py 的 8 条经验跑（它们都有人工标签，正好当标尺）：

    人工标签 17 个 → 规则全打到了（召回 8/8 条、17/17 个）
    规则一共打了 21 个 → 多打 4 个（准确率 17/21 ≈ 0.81）

多打的那 4 个：exp-1 多了「场地」（正文提了教室）、exp-2 多了
「投影仪 + 设备」（正文说「有投影和音响」）、exp-6 多了「沟通」
（正文说「在群里说一声」）。都算不上错，只是比人写得宽。

★ 但这组数字**不是准确率**，是「没退步的下限」——
  词表就是照着这 8 条写出来的，等于拿训练集当测试集。
  真实语料第一次跑的时候要重新量一遍，量出来的才是数。
  （这条比数字本身重要：把调参结果当成绩汇报，是这个项目里最容易犯的错。）
"""
from typing import Final

from .keywords import TAG_KEYWORDS

# 一条经验最多打几个标签。超了就按 keywords.py 里的顺序截断（顺序 = 优先级）。
# 定在 4：标签是用来筛的，一条经验挂七八个标签就筛不动了——
# 挂得越多，越等于没挂。
MAX_TAGS: Final[int] = 4

# CLI 的 --tagger 取值。放这里而不是放 cli/exp.py，
# 是为了让「llm 未实现」这件事能被纯函数测试钉住，不用绕到命令行。
TAGGER_NAMES: Final[tuple[str, ...]] = ("rules", "llm")


class TaggerNotImplemented(Exception):
    """请求了还没实现的打标器。

    ★ 单独一个异常类型、而不是返回空列表或悄悄用规则版顶上：
      「llm 打标器」和「规则打标器」给出的是**不同的标签**。
      静默回退会让机器人以为用的是大模型，从而对结果更信任——
      错得比直接报错严重得多。
    """


def tag(content: str) -> list[str]:
    """正文 → 该打哪些标签。纯函数，顺序固定，**不修改任何东西**。

    实现就是子串包含：对每个标签，看它的关键词有没有一个出现在正文里。
    命中的标签按 TAG_KEYWORDS 的顺序收集，超过 MAX_TAGS 个从后往前截断。

    注意这里**没有**用 set 去重：顺序本身就是输出的一部分（见文件头）。
    用 `if name not in hit` 保序去重，代价是 O(n²)，而 n ≤ 16，
    比调试一个「顺序偶尔会变」的 bug 便宜得多。
    """
    hit: list[str] = []
    for name, keywords in TAG_KEYWORDS.items():
        if any(keyword in content for keyword in keywords):
            if name not in hit:
                hit.append(name)
    return hit[:MAX_TAGS]


def ensure_available(tagger: str) -> None:
    """确认这个打标器能用。**发任何请求之前**先调它。

    单独抽出来是为了让调用方能在「还没开始扫库」的时候就失败——
    不然 `--tagger llm` 会先把整个库扫一遍，再告诉你这个打标器没有。
    """
    if tagger not in TAGGER_NAMES:
        raise ValueError(f"不认识的打标器：{tagger}（可选 {'/'.join(TAGGER_NAMES)}）")
    if tagger == "llm":
        raise TaggerNotImplemented(
            "llm 打标器还没实现。一期没有能跑大模型的机器"
            "（服务在 M710q 上，纯 CPU），而且批量打标要的是"
            "「同一条经验每次跑出来一样」，大模型做不到。"
            "要打标请用 --tagger rules。"
        )


def tag_with(tagger: str, content: str) -> list[str]:
    """按名字选打标器。目前只有 rules 是真的。

    `llm` 会抛 TaggerNotImplemented——**不是**回退到规则版。
    理由见 TaggerNotImplemented 的 docstring。
    """
    ensure_available(tagger)
    return tag(content)
